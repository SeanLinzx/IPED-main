function applyLanguage(lang) {
  activeLanguage = lang;
  const strings = Object.assign({}, dictionary[lang], siteMetaOf(lang));
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  applySiteAssets();
  document.querySelectorAll("[data-zh][data-en]").forEach((node) => {
    node.textContent = node.dataset[lang] || node.dataset.zh;
  });

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (strings[key]) {
      node.textContent = strings[key];
    }
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    node.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attr, key] = pair.split(":").map((item) => item.trim());
      if (attr && key && strings[key]) {
        node.setAttribute(attr, strings[key]);
      }
    });
  });

  buttons.forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem("til-language", lang);
  syncActiveDemoText();
  syncPressureText();
  if (typeof renderHomeCarousel === "function") {
    renderHomeCarousel();
  }
  if (typeof renderHomeIndex === "function") {
    renderHomeIndex();
  }
  if (typeof renderResearchList === "function") {
    renderResearchList();
  }
  if (typeof renderProjectDetail === "function") {
    renderProjectDetail();
  }
  if (typeof renderPublications === "function") {
    renderPublications();
  }
}

