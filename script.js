function syncActiveDemoText() {
  const activeDemo = document.querySelector(".demo-node.active, .scene-tab.active");
  const titleNode = document.querySelector("[data-demo-title]");
  const bodyNode = document.querySelector("[data-demo-body]");

  if (!activeDemo || !titleNode || !bodyNode) {
    return;
  }

  const strings = dictionary[activeLanguage];
  titleNode.textContent = strings[activeDemo.dataset.titleKey] || titleNode.textContent;
  bodyNode.textContent = strings[activeDemo.dataset.bodyKey] || bodyNode.textContent;
}

function syncPressureText() {
  if (!pressureControl) {
    return;
  }

  const value = Number(pressureControl.value);
  const titleNode = document.querySelector("[data-pressure-title]");
  const bodyNode = document.querySelector("[data-pressure-body]");
  const softDemo = document.querySelector(".soft-demo");
  const level = value < 34 ? "Low" : value > 72 ? "High" : "Medium";
  const strings = dictionary[activeLanguage];

  softDemo?.style.setProperty("--pressure", `${value}%`);
  if (titleNode) {
    titleNode.textContent = strings[`pressure${level}Title`];
  }
  if (bodyNode) {
    bodyNode.textContent = strings[`pressure${level}Body`];
  }
}

demoNodes.forEach((node) => {
  node.addEventListener("click", () => {
    const group = node.classList.contains("scene-tab") ? ".scene-tab" : ".demo-node";
    document.querySelectorAll(group).forEach((item) => item.classList.remove("active"));
    node.classList.add("active");
    syncActiveDemoText();
  });
});

pressureControl?.addEventListener("input", syncPressureText);

applyLanguage(activeLanguage);

function updateProgress() {
  const scrollable = document.documentElement.scrollHeight - window.innerHeight;
  const ratio = scrollable > 0 ? window.scrollY / scrollable : 0;
  progress.style.transform = `scaleX(${Math.min(Math.max(ratio, 0), 1)})`;
}

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { rootMargin: "0px 0px -12% 0px", threshold: 0.12 }
);

revealItems.forEach((item) => revealObserver.observe(item));

window.addEventListener("scroll", updateProgress, { passive: true });
updateProgress();

if (window.matchMedia("(pointer: fine)").matches) {
  window.addEventListener(
    "pointermove",
    (event) => {
      cursor.style.setProperty("--cursor-x", `${event.clientX}px`);
      cursor.style.setProperty("--cursor-y", `${event.clientY}px`);
      cursor.classList.add("is-active");
    },
    { passive: true }
  );

  document.querySelectorAll("a, button, .project-card, .person-card").forEach((element) => {
    element.addEventListener("pointerenter", () => cursor.classList.add("is-expanded"));
    element.addEventListener("pointerleave", () => cursor.classList.remove("is-expanded"));
  });

  tiltCards.forEach((card) => {
    card.addEventListener("pointermove", (event) => {
      const rect = card.getBoundingClientRect();
      const x = (event.clientX - rect.left) / rect.width - 0.5;
      const y = (event.clientY - rect.top) / rect.height - 0.5;
      card.style.setProperty("--tilt-x", `${-y * 8}deg`);
      card.style.setProperty("--tilt-y", `${x * 10}deg`);
      card.style.setProperty("--glow-x", `${(x + 0.5) * 100}%`);
      card.style.setProperty("--glow-y", `${(y + 0.5) * 100}%`);
    });

    card.addEventListener("pointerleave", () => {
      card.style.setProperty("--tilt-x", "0deg");
      card.style.setProperty("--tilt-y", "0deg");
    });
  });
}
